#!/usr/bin/env bash
# Modified-by: FreeANDIY (Free Andy Agency), 2026. New file, not part of upstream.
#
# Rebuild the branded tree from upstream + freeandiy/ and commit it onto `main`.
#
#   freeandiy/scripts/regenerate.sh [--check] [--keep] [UPSTREAM_REF]
#
#   UPSTREAM_REF  upstream commit to build on (default: upstream-main; with --check: the commit
#                 recorded in HEAD's .freeandiy-upstream)
#   --check       don't commit: exit 1 if HEAD's tree differs from the regenerated one (CI)
#   --keep        keep the temporary worktree for inspection
#
# How it works: a temporary worktree is checked out at UPSTREAM_REF (pristine upstream), the
# current freeandiy/ directory is copied in, `rebrand apply` runs there, and the resulting tree is
# committed on top of HEAD. When UPSTREAM_REF is not yet an ancestor of HEAD the commit is a merge
# (parents: HEAD and UPSTREAM_REF), so `git log` shows which upstream each build contains and
# upstream's history stays reachable. No conflicts, no force-push: files outside freeandiy/ are
# always regenerated, so never edit them by hand on `main`.
set -euo pipefail

CHECK=0 KEEP=0 REF=
for a in "$@"; do
  case "$a" in
    --check) CHECK=1 ;;
    --keep) KEEP=1 ;;
    -*) echo "unknown option $a" >&2; exit 2 ;;
    *) REF="$a" ;;
  esac
done

. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cd "$ROOT"
UPSTREAM_NAME="$(fa_get this.upstream_name)"
if [ -z "$REF" ]; then
  if [ "$CHECK" = 1 ] && git cat-file -e HEAD:.freeandiy-upstream 2>/dev/null; then
    REF="$(git show HEAD:.freeandiy-upstream | tr -d '[:space:]')"
  else
    REF=upstream-main
  fi
fi
UPSTREAM="$(git rev-parse --verify "$REF^{commit}")"
if [ "$CHECK" = 0 ] && [ -n "$(git status --porcelain)" ]; then
  echo "error: working tree not clean; commit your freeandiy/ changes first" >&2
  exit 1
fi

WORK="$(mktemp -d "${TMPDIR:-/tmp}/freeandiy-regen.XXXXXX")"
cleanup() {
  if [ "$KEEP" = 1 ]; then echo "kept worktree: $WORK/tree"; return; fi
  git worktree remove --force "$WORK/tree" >/dev/null 2>&1 || true
  rm -rf "${WORK:?}"
}
trap cleanup EXIT

git worktree add --detach --quiet "$WORK/tree" "$UPSTREAM"
rsync -a --delete --exclude 'tools/rebrand/target/' --exclude '.venv/' "$ROOT/freeandiy/" "$WORK/tree/freeandiy/"

"$REBRAND" apply "$WORK/tree"
# Text replacements change line lengths: keep the tree rustfmt-clean (upstream CI checks it).
(cd "$WORK/tree" && cargo fmt --all)
# Which upstream commit this tree is built from (CI's --check reads it back).
git rev-parse "$UPSTREAM" >"$WORK/tree/.freeandiy-upstream"

git -C "$WORK/tree" add -A
TREE="$(git -C "$WORK/tree" write-tree)"

if [ "$CHECK" = 1 ]; then
  if [ "$TREE" = "$(git rev-parse 'HEAD^{tree}')" ]; then
    echo "ok: HEAD matches upstream $(git rev-parse --short "$UPSTREAM") + freeandiy/"
    exit 0
  fi
  echo "error: HEAD differs from the regenerated tree (files outside freeandiy/ edited by hand, or not regenerated):" >&2
  git diff --stat HEAD "$TREE" >&2
  exit 1
fi

if [ "$TREE" = "$(git rev-parse 'HEAD^{tree}')" ]; then
  echo "nothing to do: HEAD already matches"
  exit 0
fi

PARENTS=(-p HEAD)
if ! git merge-base --is-ancestor "$UPSTREAM" HEAD; then
  PARENTS+=(-p "$UPSTREAM")
fi
MSG="brand: regenerate from upstream $(git rev-parse --short "$UPSTREAM")

Tree = upstream $UPSTREAM_NAME $(git rev-parse --short "$UPSTREAM") + freeandiy/ (rebrand apply).
Generated by freeandiy/scripts/regenerate.sh."
COMMIT="$(git commit-tree "$TREE" "${PARENTS[@]}" -m "$MSG")"
git reset --quiet --hard "$COMMIT"
echo "committed $(git rev-parse --short HEAD): upstream $(git rev-parse --short "$UPSTREAM") + freeandiy/"
